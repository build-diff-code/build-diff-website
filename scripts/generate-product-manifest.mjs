// node scripts/generate-product-manifest.mjs
// Scans public/products/*.{jpg,png,webp}, reads real dimensions, and writes
// src/data/products.ts. Slug + name are derived from the filename
// (e.g. "oak-side-table.jpg" -> slug "oak-side-table", name "Oak Side Table").
// Price/description are left as placeholders — fill those in by hand after.

import fs from "node:fs";
import path from "node:path";
import { imageSize } from "image-size";

const IMG_DIR = "./public/products";
const OUT_PATH = "./src/data/products.ts";

const files = fs
  .readdirSync(IMG_DIR)
  .filter((f) => /\.(jpe?g|png|webp)$/i.test(f))
  .sort();

if (!files.length) {
  console.error(`No images found in ${IMG_DIR}. Add some and re-run.`);
  process.exit(1);
}

const toSlug = (base) => base.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");
const toName = (base) =>
  base.replace(/[-_]+/g, " ").replace(/\b\w/g, (c) => c.toUpperCase());

const entries = files.map((file) => {
  const base = file.replace(/\.[^.]+$/, "");
  const buffer = fs.readFileSync(path.join(IMG_DIR, file));
  const { width, height } = imageSize(buffer);
  return {
    slug: toSlug(base),
    name: toName(base),
    price: "$0",
    description: "TODO: add description",
    url: `products/${file}`,
    width,
    height,
  };
});

const body = entries
  .map(
    (e) => `  {
    slug: ${JSON.stringify(e.slug)},
    name: ${JSON.stringify(e.name)},
    price: ${JSON.stringify(e.price)},
    description: ${JSON.stringify(e.description)},
    url: ${JSON.stringify(e.url)},
    width: ${e.width},
    height: ${e.height},
  },`,
  )
  .join("\n");

const output = `export type Product = {
  slug: string;
  name: string;
  price: string;
  description: string;
  url: string;
  width: number;
  height: number;
};

// Auto-generated by scripts/generate-product-manifest.mjs
// Fill in price/description per product, then leave the rest alone.
export const products: Product[] = [
${body}
];
`;

fs.writeFileSync(OUT_PATH, output);
console.log(`Wrote ${entries.length} products to ${OUT_PATH}`);
